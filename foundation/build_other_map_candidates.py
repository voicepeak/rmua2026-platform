"""Extract independent per-map road/building candidates from serialized UE maps.

These are static candidates, not verified collision scenes. In particular, no
map is generated by transforming OL1 and other obstacle categories are omitted.
"""
import argparse
import hashlib
import json
from pathlib import Path

from foundation import building_components, building_placements, road_instances, road_scene


def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def run(source, assets, output):
    raw = source.read_bytes()
    source_hash = hashlib.sha256(raw).hexdigest()
    data = json.loads(raw)
    del raw
    blueprints = {f.stem: json.loads(f.read_bytes()) for f in sorted((assets / 'blueprints').glob('*.json'))}
    mesh_path = assets / 'mesh_collision' / 'inventory.json'
    mesh_inventory = json.loads(mesh_path.read_bytes())
    templates = {name: road_scene.template_fields(assets / file, component)
                 for name, file, component in (
                     ('BP_Segment_Rot_C', 'BP_Segment_Rot.json', 'Segment_GEN_VARIABLE'),
                     ('BP_Segment_Half_C', 'BP_Segment_Half.json', 'Segment_Half_GEN_VARIABLE'))}
    chains = road_instances.build(data, source_hash)
    roads = road_scene.instances(chains, templates)
    inventory = building_components.build(data, blueprints, source_hash)
    buildings = building_placements.build(inventory, blueprints, mesh_inventory)
    missing_blueprints = [x['actor'] for x in inventory['actors'] if x['status'] != 'inventoried']
    output.mkdir(parents=True, exist_ok=True)
    sources = {'map_json': source_hash, 'mesh_inventory': digest(mesh_path),
               'road_blueprints': {name: digest(assets / name) for name in ('BP_Segment_Rot.json', 'BP_Segment_Half.json')},
               'building_blueprints': {p.name: digest(p) for p in sorted((assets / 'blueprints').glob('*.json'))}}
    common = {'status': 'unverified static candidates, not official collision coverage',
              'source_file': source.name, 'source_sha256': sources,
              'generator_sha256': {p.name: digest(p) for p in (Path(__file__), Path(road_instances.__file__),
                                   Path(road_scene.__file__), Path(building_components.__file__),
                                   Path(building_placements.__file__))},
              'missing_blueprint_actors': missing_blueprints,
              'limitations': ['serialized transforms and template defaults only',
                              'runtime construction and collision channels not verified',
                              'gates, sprites, racks, road auxiliary shapes and other actors omitted']}
    road_out = {**common, 'frame': 'UE world centimetres', 'instances': roads}
    building_out = {**common, **buildings}
    for name, obj in (('road_candidates.json', road_out), ('building_candidates.json', building_out)):
        (output / name).write_text(json.dumps(obj, separators=(',', ':'), allow_nan=False) + '\n', encoding='utf-8')
    return {'map': source.name, 'roads': len(roads), 'building_actors': len(inventory['actors']),
            'missing_blueprints': missing_blueprints,
            'building_components': len(buildings['placements']), 'unresolved': len(buildings['unresolved']),
            'outputs': {name: digest(output / name) for name in ('road_candidates.json', 'building_candidates.json')}}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('source', type=Path)
    p.add_argument('output', type=Path)
    p.add_argument('--assets', type=Path, default=Path('foundation/asset_analysis'))
    a = p.parse_args()
    print(json.dumps(run(a.source, a.assets, a.output), ensure_ascii=False))


if __name__ == '__main__':
    main()
